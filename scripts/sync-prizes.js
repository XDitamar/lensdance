// node scripts/sync-prizes.js
// Regenerates the copies of api/_prizes.js (the source of truth for the odds,
// the end dates and the Cloud Functions region):
//   src/config/prizes.js   the browser copy (CRA cannot import from outside src/)
//   functions/prizes.js    the Cloud Functions copy (the functions/ folder is
//                          deployed on its own, so it cannot reach ../api)
// src/config/prizes.test.js fails if either copy ever differs.
const fs = require("fs");
const path = require("path");
const { PRIZES, TOTAL_WEIGHT, PRIZE_WHEEL_UNTIL, PRIZE_VALID_UNTIL, FUNCTIONS_REGION } = require("../api/_prizes");

const lines = PRIZES.map((p) => `  ${JSON.stringify(p)},`).join("\n");

const out = `// src/config/prizes.js
//
// GENERATED by scripts/sync-prizes.js from api/_prizes.js: do not edit by hand.
// api/_prizes.js is the source of truth for the odds; CRA cannot import from
// outside src/, so the table is copied here and src/config/prizes.test.js fails
// if the two differ. Change api/_prizes.js, then run \`node scripts/sync-prizes.js\`.

import { PRIZE_WHEEL_UNTIL, PRIZE_VALID_UNTIL } from "./features";

export { PRIZE_WHEEL_UNTIL, PRIZE_VALID_UNTIL };

export const TOTAL_WEIGHT = ${TOTAL_WEIGHT};

/** The Cloud Functions region the wheel is deployed to (one constant, see api/_prizes.js). */
export const FUNCTIONS_REGION = "${FUNCTIONS_REGION}";

export const PRIZES = [
${lines}
];

export const prizeById = (id) => PRIZES.find((p) => p.id === id) || null;
export const isCapped = (id) => !!prizeById(id)?.capped;

/** The calendar date in Israel, "YYYY-MM-DD". */
export function israelDay(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Jerusalem",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
}

/** Is the wheel still open? Same rule as the server, on the visitor's clock. */
export const wheelOpen = (now = new Date()) => israelDay(now) <= PRIZE_WHEEL_UNTIL;

/** Has a prize that was valid until \`validUntil\` run out? */
export const isExpired = (validUntil, now = new Date()) => !validUntil || israelDay(now) > validUntil;

/** 2026-12-31 -> 31.12.2026 (numeric, so it reads the same in every language). */
export const dmy = (iso) => String(iso).split("-").reverse().join(".");
`;
fs.writeFileSync(path.join(__dirname, "../src/config/prizes.js"), out);
console.log("wrote src/config/prizes.js");

const fnOut = `// functions/prizes.js
//
// GENERATED by scripts/sync-prizes.js from api/_prizes.js: do not edit by hand.
// The functions/ folder is deployed on its own, so the prizes table, the dates
// and the region are copied here. src/config/prizes.test.js fails on any drift.

const PRIZES = [
${lines}
];

module.exports = {
  PRIZES,
  TOTAL_WEIGHT: ${TOTAL_WEIGHT},
  PRIZE_WHEEL_UNTIL: ${JSON.stringify(PRIZE_WHEEL_UNTIL)},
  PRIZE_VALID_UNTIL: ${JSON.stringify(PRIZE_VALID_UNTIL)},
  FUNCTIONS_REGION: ${JSON.stringify(FUNCTIONS_REGION)},
};
`;
fs.writeFileSync(path.join(__dirname, "../functions/prizes.js"), fnOut);
console.log("wrote functions/prizes.js");
